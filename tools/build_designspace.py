#!/usr/bin/env python3
"""
Build js/designspace_data.js for the viewer's Design space tab: every die organisation that reaches 32 Gb/s on the
HBM4 interface with a 64 B column access (tools/sweep_interface.py option a64), plus the row-activation numbers that
motivate the wider access.

A design is kept when it passes with an I/O sense amp per bank, with or without a mid-bank column decoder (none pass
with the sense amp shared at the I/O control). Geometry, power and fault coverage do not depend on that choice.

Usage:
  python3 tools/build_designspace.py --dreamram /path/to/DreamRAM [--rate 32] [--tsv-rate 8]
"""
import argparse
import contextlib
import io
import json
import os
import sys
import types

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import export_floorplan as E  # noqa: E402
import sweep_interface as SI  # noqa: E402
import sweep_pin_rate as SW  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KEYS = ['vert_bg', 'horiz_bg', 'banks', 'subarrays', 'mats', 'mat_cols', 'mat_rows', 'ldls_mdls', 'mdlcsl',
        'csl_mdl_shared_layer', 'brvsa', 'coupled_rows', 'channel_rows']


def activation(a, name, rate):
    """Row-activation limits of a bundled design: tRRD, tFAW and per-command energies from DreamRAM."""
    ex = json.load(open(os.path.join(ROOT, 'examples', name + '.json')))
    with contextlib.redirect_stdout(io.StringIO()):
        dram, tech, _, m, _ = E.build(a.dreamram, SW.MEM, SW.TECH, dict(ex['params']), 40)
    p = ex['params']
    dq_pc = dram.dq_count() / (p['channels'] * p['pch']) / dram.md_ecc_factor()
    tfaw = dram.tfaw(tech)
    bytes_per_act = dq_pc * rate / 8 * tfaw / 4  # bytes a pseudo-channel moves per activation it may issue
    return dict(name=name, rate=rate, access=p['atom_size'] // 8, trrd=round(float(dram.trrds(tech)), 2), tfaw=round(float(tfaw), 2),
                bytes_per_act=round(float(bytes_per_act)), reads32=round(float(bytes_per_act / 32), 1),
                e_act=round(float(m['e_cmd_act_pj'])), e_pre=round(float(m['e_cmd_pre_pj'])), e_rd=round(float(m['e_cmd_rd_pj'])))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--dreamram', required=True)
    ap.add_argument('--rate', type=float, default=32)
    ap.add_argument('--tsv-rate', type=float, default=8)
    ap.add_argument('--max-die-mm', type=float, default=20)
    ap.add_argument('-o', '--out', default=os.path.join(ROOT, 'js', 'designspace_data.js'))
    a = ap.parse_args()
    a.dreamram = os.path.abspath(a.dreamram)
    sa = types.SimpleNamespace(dreamram=a.dreamram, tsv_rate=a.tsv_rate, max_die_mm=a.max_die_mm)
    pch, access, bgs, banks_pc, _ = SI.OPTIONS['a64']
    designs = {}
    for d in SI.internal_designs(pch, bgs, banks_pc, access):
        for model in ('staged_bank', 'staged_bank_mid'):
            r = SI.evaluate(sa, 'a64', d, model, a.rate)
            if not r or r['rmax'] < a.rate - 1e-9:
                continue
            key = tuple(r[k] for k in KEYS)
            pt = designs.setdefault(key, dict(
                **{k: r[k] for k in KEYS}, die=round(r['die'], 2), w=round(r['die_w'], 2), h=round(r['die_h'], 2),
                aspect=round(r['aspect'], 3), power=round(r['power'], 1), cell=round(100 * r['cell_eff'], 2),
                lat=round(r['latency'], 1), hits=r['fault_hits'], t=r['fault_t'], tsvs=r['tsvs_pc'], bank=False))
            if model == 'staged_bank':
                pt['bank'], pt['tccdl'] = True, round(r['tccdl'], 3)
            else:
                pt.setdefault('tccdl', round(r['tccdl'], 3))
    pts = sorted(designs.values(), key=lambda p: (p['die'], p['power']))
    out = dict(rate=a.rate, tsv_rate=a.tsv_rate, footprint=[14.175, 10.975], designs=pts,
               activation=[activation(a, 'hbm4_1sid_coupled', 8), activation(a, 'g32_2bg_staged_bank', a.rate)])
    with open(a.out, 'w') as fh:
        fh.write('// Generated by tools/build_designspace.py (DreamRAM + staged tCCD_L). Do not edit.\n')
        fh.write('window.DR_DESIGNSPACE = ' + json.dumps(out, separators=(',', ':')) + ';\n')
    print('wrote', a.out, len(pts), 'designs')


if __name__ == '__main__':
    main()
