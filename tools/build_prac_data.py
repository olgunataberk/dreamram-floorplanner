#!/usr/bin/env python3
"""
Build js/prac_data.js for the viewer's PRAC tab from the two studies:
- tools/prac_study.py: PRAC design decisions and OD-ECC engines on bundled designs;
- tools/hbm5_study.py: HBM5 with 2x channels per die at 8 Gb/s (HBM4 ECC) and 16 Gb/s (HBM4 ECC, two pipeline stages).

Usage:
  python3 tools/build_prac_data.py --dreamram /path/to/DreamRAM
"""
import argparse
import json
import os
import sys
import types

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import export_floorplan as E  # noqa: E402
import hbm5_study as H5  # noqa: E402
import prac_study as PS  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DESIGNS = ['hbm3_baseline', 'hbm4_1sid_coupled', 'hbm5_2bg_min_area', 'g32_64b_fp5_lowpower']


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--dreamram', required=True)
    ap.add_argument('-o', '--out', default=os.path.join(ROOT, 'js', 'prac_data.js'))
    a = types.SimpleNamespace(dreamram=os.path.abspath(ap.parse_args().dreamram), tsv_rate=8, max_die_mm=20)
    out_path = ap.parse_args().out
    data = dict(
        ddr5=E.DDR5_PRAC, prac_constants=E.PRAC, circ=E.CIRC, level_fo4=E.LEVEL_FO4,
        designs=PS.study(a, DESIGNS),
        hbm5=[H5.study(a, 8, 16, 1), H5.study(a, 16, 16, 2)],
    )
    with open(out_path, 'w') as fh:
        fh.write('// Generated by tools/build_prac_data.py (tools/prac_study.py + tools/hbm5_study.py). Do not edit.\n')
        fh.write('window.DR_PRAC = ' + json.dumps(data, separators=(',', ':')) + ';\n')
    print('wrote', out_path)


if __name__ == '__main__':
    main()
