#!/usr/bin/env python3
"""Bundle examples/*.json into js/examples.js so the viewer also works from file:// (no fetch)."""
import glob
import json
import os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ex = {}
for path in sorted(glob.glob(os.path.join(root, 'examples', '*.json'))):
    ex[os.path.splitext(os.path.basename(path))[0]] = json.load(open(path))
with open(os.path.join(root, 'js', 'examples.js'), 'w') as fh:
    fh.write('// Generated by tools/build_examples.py from examples/*.json (DreamRAM exports). Do not edit.\n')
    fh.write('window.DR_EXAMPLES = ' + json.dumps(ex, separators=(',', ':')) + ';\n')
print('bundled', ', '.join(ex))
